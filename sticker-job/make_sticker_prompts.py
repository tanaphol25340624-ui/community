def make_prompt(sticker, style_prompt):
    return f"""\
{style_prompt}

ข้อความบนสติ๊กเกอร์ต้องเขียนว่า:
"{sticker['phrase']}"

ท่าทางและสีหน้า:
{sticker['pose']}

จัดคำพูดให้อยู่ใกล้ตัวละครและอ่านได้ชัด
ห้ามมีข้อความอื่นนอกเหนือจากข้อความที่กำหนด
สร้างเป็นสติ๊กเกอร์เดี่ยว 1 แบบต่อ 1 ภาพ"""


def main():
    parser = argparse.ArgumentParser(
        description="สร้างและพิมพ์พรอมป์ต์สำหรับสติ๊กเกอร์ทั้ง 24 แบบ"
    )
    parser.add_argument(
        "--style-prompt",
        default="สไตล์สติ๊กเกอร์การ์ตูนน่ารัก สีสันสดใส",
        help="คำอธิบายสไตล์ภาพ",
    )
    args = parser.parse_args()

    for index, sticker in enumerate(STICKERS, start=1):
        print(f"--- สติ๊กเกอร์ที่ {index} ---")
        print(make_prompt(sticker, args.style_prompt))
        if index < len(STICKERS):
            print()


if __name__ == "__main__":
    main()
